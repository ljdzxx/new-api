package controller

import (
	"net/http"

	"github.com/QuantumNous/new-api/model"
	"github.com/QuantumNous/new-api/service"
	"github.com/QuantumNous/new-api/setting"
	"github.com/QuantumNous/new-api/setting/ratio_setting"

	"github.com/gin-gonic/gin"
)

func GetGroups(c *gin.Context) {
	groupNames := make([]string, 0)
	for groupName := range ratio_setting.GetGroupRatioCopy() {
		groupNames = append(groupNames, groupName)
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    groupNames,
	})
}

func GetUserGroups(c *gin.Context) {
	usableGroups := make(map[string]map[string]interface{})
	userGroup := ""
	userId := c.GetInt("id")
	userGroup, _ = model.GetUserGroup(userId, false)
	userUsableGroups := service.GetUserUsableGroups(userGroup)
	for groupName := range ratio_setting.GetGroupRatioCopy() {
		// UserUsableGroups contains the groups that the user can use
		if desc, ok := userUsableGroups[groupName]; ok {
			baseRatio := ratio_setting.GetGroupRatio(groupName)
			effectiveRatio := service.GetUserGroupRatio(userGroup, groupName)
			info := map[string]interface{}{
				"ratio": effectiveRatio,
				"desc":  desc,
				"icon":  ratio_setting.GetGroupIcon(groupName),
			}
			// 分组特殊倍率生效时，额外返回原始倍率，前端用删除线展示原价
			if _, hasSpecial := ratio_setting.GetGroupGroupRatio(userGroup, groupName); hasSpecial && effectiveRatio != baseRatio {
				info["original_ratio"] = baseRatio
			}
			usableGroups[groupName] = info
		}
	}
	if _, ok := userUsableGroups["auto"]; ok {
		usableGroups["auto"] = map[string]interface{}{
			"ratio": "自动",
			"desc":  setting.GetUsableGroupDescription("auto"),
			"icon":  ratio_setting.GetGroupIcon("auto"),
		}
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    usableGroups,
	})
}
